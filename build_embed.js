// LODU — Build: canonical engine -> browser-embedded engine.
// This is Option A from the Phase B checkpoint: the embedded copy is
// MECHANICALLY GENERATED from board.js/rules.js (only the CommonJS
// require()/module.exports wrapper is swapped for an IIFE/return — no
// logic is retyped by hand), so the two can no longer independently
// drift. Run: node build_embed.js
'use strict';

const fs = require('fs');
const path = require('path');

function toIIFEBody(source, { stripRequireLine }) {
  let body = source;
  if (stripRequireLine) {
    // Board is already in scope as the enclosing const in the generated
    // output (see bottom of this file), so the require() line is dropped.
    body = body.replace(/^const Board = require\('\.\/board'\);\n\n?/m, '');
  }
  // module.exports = { ... }; -> return { ... };  (mechanical only)
  body = body.replace(/module\.exports = (\{[\s\S]*?\});\s*$/, 'return $1;');
  return body.trim();
}

function indent(text, spaces) {
  const pad = ' '.repeat(spaces);
  return text.split('\n').map((line) => (line.length ? pad + line : line)).join('\n');
}

const boardSrc = fs.readFileSync(path.join(__dirname, 'board.js'), 'utf8');
const rulesSrc = fs.readFileSync(path.join(__dirname, 'rules.js'), 'utf8');

const boardBody = toIIFEBody(boardSrc, { stripRequireLine: false });
const rulesBody = toIIFEBody(rulesSrc, { stripRequireLine: true });

const output = [
  '/* === EMBEDDED-ENGINE-START (auto-generated by build_embed.js from board.js + rules.js — do not hand-edit) === */',
  'const Board = (() => {',
  indent(boardBody, 2),
  '})();',
  '',
  'const Rules = (() => {',
  indent(rulesBody, 2),
  '})();',
  '/* === EMBEDDED-ENGINE-END === */',
].join('\n');

fs.writeFileSync(path.join(__dirname, 'embedded_engine.generated.js'), output);
console.log(`Wrote embedded_engine.generated.js (${output.length} chars).`);
console.log('Paste this block into the HTML between the EMBEDDED-ENGINE-START/END markers.');
